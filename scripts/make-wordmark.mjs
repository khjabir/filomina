#!/usr/bin/env node
/**
 * Builds the Filomina wordmark as vector art:
 *   - "ilomin" are the real Nunito ExtraBold outlines (from @fontsource/nunito)
 *   - "F" is a drawn gradient ribbon (from the reference logo)
 *   - "a" is drawn as a lens with a magnifier handle (echoes the icon)
 * Outputs components/brand/WordmarkArt.tsx (theme-aware, currentColor letters)
 * and public/brand/wordmark.svg / wordmark-light.svg for raster use.
 */
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
const fontkit = createRequire(import.meta.url)("fontkit");

const font = fontkit.openSync("node_modules/@fontsource/nunito/files/nunito-latin-800-normal.woff2");
const r = (n) => Math.round(n * 10) / 10;

/** Glyph path → SVG path string, shifted by dx, y flipped (baseline at y = 0). */
function glyphPath(glyph, dx) {
  let d = "";
  for (const c of glyph.path.commands) {
    const a = c.args.map((v, i) => r(i % 2 === 0 ? v + dx : -v));
    if (c.command === "moveTo") d += `M${a[0]} ${a[1]}`;
    else if (c.command === "lineTo") d += `L${a[0]} ${a[1]}`;
    else if (c.command === "quadraticCurveTo") d += `Q${a[0]} ${a[1]} ${a[2]} ${a[3]}`;
    else if (c.command === "bezierCurveTo") d += `C${a[0]} ${a[1]} ${a[2]} ${a[3]} ${a[4]} ${a[5]}`;
    else if (c.command === "closePath") d += "Z";
  }
  return d;
}

const iGlyph = font.layout("i").glyphs[0];
const stem = iGlyph.bbox.maxX - iGlyph.bbox.minX; // stroke weight of the typeface (≈ 180)

/* ── F: gradient ribbon ───────────────────────────────────────────── */
const F_ADVANCE = 690;
const fStroke = stem;
const fx = fStroke / 2 + 70;
const fPaths = [
  `M${fx} ${-705 + fStroke / 2} L${fx} -150 Q${fx} -30 ${r(fx - 95)} 18`, // stem with a sweep to the left
  `M${fx} ${-705 + fStroke / 2} L${r(fx + 390)} ${-705 + fStroke / 2}`, // top arm
  `M${fx} -355 L${r(fx + 300)} -355`, // middle arm
];

/* ── i l o m i n: real outlines ───────────────────────────────────── */
const run = font.layout("ilomin");
let x = F_ADVANCE;
const letterPaths = [];
run.glyphs.forEach((g, i) => {
  letterPaths.push(glyphPath(g, x));
  x += run.positions[i].xAdvance;
});
const A_START = x + 10;

/* ── a: lens + handle ─────────────────────────────────────────────── */
const ring = Math.round(stem * 0.78);
const cx = A_START + 262;
const cy = -250;
const R = 258 - ring / 2; // centreline radius so the outer edge sits at x-height
const sx = A_START + 524 - stem / 2; // right stem x
const aStroke = [
  `M${sx} -470 L${sx} -110 L${r(sx + 110)} 0`, // stem that turns into a handle
];
const A_ADVANCE = 524 + 110 + 80;
const totalW = A_START + A_ADVANCE;
const viewBox = `0 -780 ${Math.round(totalW)} 880`;

const defs = `
    <linearGradient id="wmF" gradientUnits="userSpaceOnUse" x1="${r(fx + 390)}" y1="-705" x2="${r(fx - 60)}" y2="20">
      <stop offset="0" stop-color="#3B82F6"/><stop offset="0.5" stop-color="#7C3AED"/><stop offset="0.8" stop-color="#EC4899"/><stop offset="1" stop-color="#FB923C"/>
    </linearGradient>
    <linearGradient id="wmA" gradientUnits="userSpaceOnUse" x1="${r(cx - R)}" y1="${r(cy - R)}" x2="${r(sx + 110)}" y2="0">
      <stop offset="0" stop-color="#3B82F6"/><stop offset="1" stop-color="#7C3AED"/>
    </linearGradient>
    <radialGradient id="wmLens" gradientUnits="userSpaceOnUse" cx="${r(cx - 50)}" cy="${r(cy - 50)}" r="${r(R)}">
      <stop offset="0" stop-color="#1E3A8A"/><stop offset="1" stop-color="#0B1026"/>
    </radialGradient>`;

const art = (letterFill) => `
    ${fPaths.map((d) => `<path d="${d}" fill="none" stroke="url(#wmF)" stroke-width="${fStroke}" stroke-linecap="round" stroke-linejoin="round"/>`).join("\n    ")}
    <path d="${letterPaths.join(" ")}" fill="${letterFill}" fill-rule="nonzero"/>
    <circle cx="${r(cx)}" cy="${r(cy)}" r="${r(R - ring / 2)}" fill="url(#wmLens)" opacity="0.82"/>
    <circle cx="${r(cx)}" cy="${r(cy)}" r="${r(R)}" fill="none" stroke="url(#wmA)" stroke-width="${ring}"/>
    <circle cx="${r(cx - 70)}" cy="${r(cy - 70)}" r="38" fill="#fff" opacity="0.85"/>
    ${aStroke.map((d) => `<path d="${d}" fill="none" stroke="url(#wmA)" stroke-width="${stem}" stroke-linecap="round" stroke-linejoin="round"/>`).join("\n    ")}`;

const svg = (letterFill) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" fill="none">
  <defs>${defs}
  </defs>${art(letterFill)}
</svg>
`;
writeFileSync("public/brand/wordmark.svg", svg("#1B1B4F"));
writeFileSync("public/brand/wordmark-light.svg", svg("#F2F3F8"));

const tsx = `// Generated by scripts/make-wordmark.mjs – do not edit by hand.
import type { SVGProps } from "react";

export const WORDMARK_RATIO = ${r(totalW / 880)};

/** The Filomina wordmark as vector art; the plain letters use currentColor. */
export function WordmarkArt(props: SVGProps<SVGSVGElement>) {
  return (
    <svg viewBox="${viewBox}" fill="none" xmlns="http://www.w3.org/2000/svg" {...props}>
      <defs>${defs.replace(/stop-color/g, "stopColor")}
      </defs>${art("currentColor").replace(/fill-rule/g, "fillRule").replace(/stroke-width/g, "strokeWidth").replace(/stroke-linecap/g, "strokeLinecap").replace(/stroke-linejoin/g, "strokeLinejoin")}
    </svg>
  );
}
`;
writeFileSync("components/brand/WordmarkArt.tsx", tsx);
console.log(`wordmark written (stem ${stem}, width ${Math.round(totalW)})`);
